#ifndef TRAJECTORY_ANALYZER_H_
#define TRAJECTORY_ANALYZER_H_

#include <corbo-core/time_series.h>
#include <Eigen/Core>
#include <geometry_msgs/PoseStamped.h>
#include <vector>

namespace mpc_local_planner {

/**
 * @brief Utility class for analyzing predicted trajectories
 * 
 * This class provides various metrics and analysis tools for
 * trajectory predictions generated by the MPC controller.
 */
class TrajectoryAnalyzer
{
public:
    /**
     * @brief Structure to hold trajectory analysis results
     */
    struct TrajectoryMetrics
    {
        double total_time;          //!< Total trajectory duration [s]
        double total_distance;      //!< Total path length [m]
        double max_velocity;        //!< Maximum linear velocity [m/s]
        double max_acceleration;    //!< Maximum linear acceleration [m/s²]
        double max_angular_velocity; //!< Maximum angular velocity [rad/s]
        double max_curvature;       //!< Maximum trajectory curvature [1/m]
        double average_velocity;    //!< Average linear velocity [m/s]
        double smoothness;          //!< Trajectory smoothness metric (lower is smoother)
        double goal_distance_error; //!< Distance from final pose to goal [m]
        double goal_angle_error;    //!< Angular error from final pose to goal [rad]
        bool trajectory_valid;      //!< Whether trajectory is valid
        
        TrajectoryMetrics() :
            total_time(0.0), total_distance(0.0), max_velocity(0.0),
            max_acceleration(0.0), max_angular_velocity(0.0), max_curvature(0.0),
            average_velocity(0.0), smoothness(0.0), goal_distance_error(0.0),
            goal_angle_error(0.0), trajectory_valid(false) {}
    };

    /**
     * @brief Analyze a state trajectory and corresponding control sequence
     * 
     * @param x_seq State trajectory (x, y, theta)
     * @param u_seq Control sequence (v, omega)
     * @param goal_pose Optional goal pose for accuracy analysis
     * @return TrajectoryMetrics Analysis results
     */
    static TrajectoryMetrics analyzeTrajectory(const corbo::TimeSeries::Ptr& x_seq,
                                              const corbo::TimeSeries::Ptr& u_seq,
                                              const geometry_msgs::PoseStamped* goal_pose = nullptr);

    /**
     * @brief Calculate total path length from state trajectory
     * 
     * @param x_seq State trajectory
     * @return Total path length [m]
     */
    static double calculatePathLength(const corbo::TimeSeries::Ptr& x_seq);

    /**
     * @brief Calculate maximum velocity from control sequence
     * 
     * @param u_seq Control sequence
     * @return Maximum linear velocity [m/s]
     */
    static double calculateMaxVelocity(const corbo::TimeSeries::Ptr& u_seq);

    /**
     * @brief Calculate maximum acceleration from control sequence
     * 
     * @param u_seq Control sequence
     * @return Maximum linear acceleration [m/s²]
     */
    static double calculateMaxAcceleration(const corbo::TimeSeries::Ptr& u_seq);

    /**
     * @brief Calculate trajectory curvature at each point
     * 
     * @param x_seq State trajectory
     * @param curvatures Output vector of curvature values
     * @return Maximum curvature [1/m]
     */
    static double calculateCurvature(const corbo::TimeSeries::Ptr& x_seq,
                                    std::vector<double>& curvatures);

    /**
     * @brief Calculate trajectory smoothness metric
     * 
     * Smoothness is measured as the sum of squared jerk (derivative of acceleration)
     * 
     * @param u_seq Control sequence
     * @return Smoothness metric (lower values indicate smoother trajectories)
     */
    static double calculateSmoothness(const corbo::TimeSeries::Ptr& u_seq);

    /**
     * @brief Calculate goal tracking accuracy
     * 
     * @param x_seq State trajectory
     * @param goal_pose Goal pose
     * @param distance_error Output: distance error [m]
     * @param angle_error Output: angular error [rad]
     */
    static void calculateGoalAccuracy(const corbo::TimeSeries::Ptr& x_seq,
                                     const geometry_msgs::PoseStamped& goal_pose,
                                     double& distance_error,
                                     double& angle_error);

    /**
     * @brief Check if trajectory satisfies velocity and acceleration constraints
     * 
     * @param u_seq Control sequence
     * @param max_vel Maximum allowed linear velocity [m/s]
     * @param max_omega Maximum allowed angular velocity [rad/s]
     * @param max_acc Maximum allowed linear acceleration [m/s²]
     * @return True if all constraints are satisfied
     */
    static bool checkConstraints(const corbo::TimeSeries::Ptr& u_seq,
                                double max_vel = 2.0,
                                double max_omega = 2.0,
                                double max_acc = 1.0);

    /**
     * @brief Sample trajectory at regular intervals
     * 
     * @param x_seq State trajectory
     * @param dt Sampling interval [s]
     * @param sampled_poses Output: sampled poses
     */
    static void sampleTrajectory(const corbo::TimeSeries::Ptr& x_seq,
                                double dt,
                                std::vector<geometry_msgs::PoseStamped>& sampled_poses);

    /**
     * @brief Print trajectory analysis to console
     * 
     * @param metrics Trajectory metrics to print
     */
    static void printAnalysis(const TrajectoryMetrics& metrics);

    /**
     * @brief Convert trajectory metrics to string
     * 
     * @param metrics Trajectory metrics
     * @return String representation of metrics
     */
    static std::string metricsToString(const TrajectoryMetrics& metrics);

private:
    /**
     * @brief Calculate numerical derivative of time series
     * 
     * @param ts Input time series
     * @param derivative Output derivative time series
     */
    static void calculateDerivative(const corbo::TimeSeries::Ptr& ts,
                                   corbo::TimeSeries::Ptr& derivative);

    /**
     * @brief Normalize angle to [-pi, pi]
     */
    static double normalizeAngle(double angle);
};

} // namespace mpc_local_planner

#endif // TRAJECTORY_ANALYZER_H_